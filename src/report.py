"""
Generates RESULTS.md and data/monte_carlo_fcf.png from the backtest and
scenario outputs — the readable finding, not just the code that produces
it. RESULTS.md is generated, never hand-edited, so its claims always match
the last run: regenerate with `make report` after any change to
src/model.py, src/backtest.py or src/scenario.py.

Chart style matches the rest of this portfolio (same palette as
gbs-business-case's Monte Carlo chart and gbs-agentic-shift's mix chart).
"""

from __future__ import annotations

import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from src import backtest, clientpack, config as C, scenario

PALETTE = {
    "surface": "#fcfcfb",
    "ink": "#0b0b0b",
    "ink2": "#52514e",
    "muted": "#898781",
    "grid": "#e1e0d9",
    "axis": "#c3c2b7",
}
DRIVER_COLOR = "#2a78d6"
ACTUAL_COLOR = "#eb6834"


def _style(ax, fig):
    fig.patch.set_facecolor(PALETTE["surface"])
    ax.set_facecolor(PALETTE["surface"])
    for spine in ("top", "right"):
        ax.spines[spine].set_visible(False)
    for spine in ("left", "bottom"):
        ax.spines[spine].set_color(PALETTE["axis"])
    ax.tick_params(colors=PALETTE["ink2"], labelsize=9)


def plot_fcf_distribution(mc: dict, actual_fcf: float, out) -> None:
    fcfs = mc["fcf_draws"]
    p10, p50, p90 = mc["fcf_p10"], mc["fcf_p50"], mc["fcf_p90"]

    fig, ax = plt.subplots(figsize=(8, 4.5))
    _style(ax, fig)
    ax.hist(fcfs, bins=60, color=DRIVER_COLOR, alpha=0.85, edgecolor=PALETTE["surface"], linewidth=0.3)

    ax.axvline(p50, color=PALETTE["ink"], linewidth=1.2)
    ax.text(p50, ax.get_ylim()[1] * 0.95, f"  median {p50:,.0f}", color=PALETTE["ink"], fontsize=8, va="top")

    ax.axvline(actual_fcf, color=ACTUAL_COLOR, linewidth=1.5, linestyle=(0, (3, 3)))
    ax.text(actual_fcf, ax.get_ylim()[1] * 0.85, f"  actual FY2025 {actual_fcf:,.0f}",
            color=ACTUAL_COLOR, fontsize=8, va="top")

    ax.set_xlabel("Free cash flow (€ millions)", color=PALETTE["ink2"], fontsize=9)
    ax.set_ylabel("Draws", color=PALETTE["ink2"], fontsize=9)
    ax.grid(axis="y", color=PALETTE["grid"], linewidth=0.8, zorder=0)
    ax.set_axisbelow(True)
    ax.set_title(
        f"Monte Carlo FCF distribution (n={mc['n']:,}) — downside P10 {p10:,.0f}, upside P90 {p90:,.0f}",
        color=PALETTE["ink"], fontsize=10.5, loc="left",
    )
    fig.tight_layout()
    fig.savefig(out, dpi=160, facecolor=fig.get_facecolor())
    plt.close(fig)


def _fmt_pct(value: float) -> str:
    return f"{abs(value):.1f}%"


ASSUMPTION_LABELS = {
    "working_capital_pct": "working capital",
    "operating_profit_target": "operating profit target",
    "capex": "capex",
    "growth": "revenue growth",
}


def build_results_md(bt: dict, mc: dict) -> str:
    naive, driven, actual = bt["naive"], bt["driver_based"], bt["actual"]
    top_driver = next(iter(mc["sensitivity_to_fcf"]))

    lines = [
        "# Results",
        "",
        "**Scope:** adidas AG, one backtest point (built as of FY2024, checked "
        "against FY2025 actuals). Generated by `src/report.py` — regenerate "
        "with `make report` after any model change.",
        "",
        "## Bottom line",
        "",
        "The driver-based forecast beat a naive top-down extrapolation on "
        f"every backtested metric, but both undershot actual FY2025 "
        f"operating profit (€{actual['operating_profit']:,.0f}m) — adidas "
        "guided €1.7–1.8bn and delivered more. \"The driver-based model "
        "won\" is not the same claim as \"the driver-based model was "
        "accurate.\"",
        "",
        "| metric | naive error | driver-based error | actual |",
        "|---|---|---|---|",
        f"| Revenue | {_fmt_pct(naive['revenue_error_pct'])} | {_fmt_pct(driven['revenue_error_pct'])} | €{actual['revenue']:,.0f}m |",
        f"| Operating profit | {_fmt_pct(naive['operating_profit_error_pct'])} | {_fmt_pct(driven['operating_profit_error_pct'])} | €{actual['operating_profit']:,.0f}m |",
        f"| Free cash flow | {_fmt_pct(naive['free_cash_flow_error_pct'])} | {_fmt_pct(driven['free_cash_flow_error_pct'])} | €{actual['free_cash_flow']:,.0f}m |",
        "",
        "## Monte Carlo: which assumption actually drives the uncertainty",
        "",
        "![Monte Carlo free cash flow distribution](data/monte_carlo_fcf.png)",
        "",
        f"10,000 draws sampled from adidas's own disclosed FY2025 guidance "
        f"ranges — not invented historical volatility; three fiscal years "
        f"is too few to estimate that honestly (see `src/scenario.py`).",
        "",
        "| | |",
        "|---|---|",
        f"| Downside (P10) | €{mc['fcf_p10']:,.0f}m |",
        f"| Median (P50) | €{mc['fcf_p50']:,.0f}m |",
        f"| Upside (P90) | €{mc['fcf_p90']:,.0f}m |",
        f"| Actual FY2025 (derived) | €{actual['free_cash_flow']:,.0f}m |",
        "",
        "Sensitivity of simulated free cash flow to each assumption, ranked "
        "by absolute correlation:",
        "",
        "| assumption | correlation with FCF |",
        "|---|---|",
    ]
    for name, corr in mc["sensitivity_to_fcf"].items():
        lines.append(f"| {ASSUMPTION_LABELS.get(name, name)} | {corr:+.2f} |")
    lines += [
        "",
        f"**{ASSUMPTION_LABELS.get(top_driver, top_driver).capitalize()} dominates** — a wider or "
        "narrower revenue-growth assumption barely moves the free-cash-flow "
        "outcome by comparison. The naive method's biggest miss was exactly "
        "this: it held working capital flat at FY2024's level while it "
        "actually rose. Review time is better spent stress-testing the "
        "working-capital assumption than re-arguing the growth rate.",
        "",
        "## What this is not",
        "",
        "- **A track record.** One backtest point. A single win is evidence "
        "the driver-based approach beat one naive baseline once, not that "
        "it generalizes.",
        "- **Statistically estimated uncertainty.** The Monte Carlo ranges "
        "are adidas's own disclosed guidance bands, chosen because three "
        "fiscal years cannot support a real volatility estimate.",
        "",
        "---",
        "",
        "Generated by `src/report.py` from `data/facts/adidas_drivers.json`, "
        "`src/backtest.py` and `src/scenario.py`.",
        "",
    ]
    return "\n".join(lines)


def run() -> None:
    facts = json.loads((C.FACTS / "adidas_drivers.json").read_text())
    bt = backtest.run()
    mc = scenario.run_monte_carlo(clientpack.get_pack("adidas"), n=10_000, seed=0)

    plot_fcf_distribution(mc, bt["actual"]["free_cash_flow"], C.DATA / "monte_carlo_fcf.png")

    results_md = build_results_md(bt, mc)
    (C.ROOT / "RESULTS.md").write_text(results_md)


if __name__ == "__main__":
    run()
    print("Wrote RESULTS.md and data/monte_carlo_fcf.png")
